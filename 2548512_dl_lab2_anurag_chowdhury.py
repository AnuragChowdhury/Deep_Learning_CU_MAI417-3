import torch
import torch.nn as nn
import torch.nn.functional as F
import torch.optim as optim
from torchvision import datasets, transforms
from torch.utils.data import DataLoader
import matplotlib.pyplot as plt

transform = transforms.Compose([
    transforms.ToTensor(),
    transforms.Normalize((0.5,), (0.5,))
])

train_data = datasets.FashionMNIST(root='./data', train=True, transform=transform, download=True)
test_data = datasets.FashionMNIST(root='./data', train=False, transform=transform, download=True)

train_loader = DataLoader(train_data, batch_size=64, shuffle=True)
test_loader = DataLoader(test_data, batch_size=64, shuffle=False)

#At least three hidden layers with ReLU
# Input size = 28*28 = 784
layer1 = nn.Linear(784, 512)
layer2 = nn.Linear(512, 256)
layer3 = nn.Linear(256, 128)
layer4 = nn.Linear(128, 10)

#Combine all parameters for optimizer
params = list(layer1.parameters()) + list(layer2.parameters()) \
       + list(layer3.parameters()) + list(layer4.parameters())

#Loss Function & Optimizer
criterion = nn.CrossEntropyLoss()
optimizer = optim.Adam(params, lr=0.001)

#Forward Function
def forward(x):
    x = x.view(-1, 28*28)          # Flatten
    x = F.relu(layer1(x))
    x = F.relu(layer2(x))
    x = F.relu(layer3(x))
    x = layer4(x)
    return x

#Training
epochs = 10
train_losses = []
train_accuracies = []

for epoch in range(epochs):
    running_loss = 0
    correct = 0
    total = 0

    for images, labels in train_loader:
        outputs = forward(images)
        loss = criterion(outputs, labels)

        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        running_loss += loss.item()

        _, predicted = torch.max(outputs, 1)
        total += labels.size(0)
        correct += (predicted == labels).sum().item()

    acc = 100 * correct / total
    train_losses.append(running_loss / len(train_loader))
    train_accuracies.append(acc)

    print(f"Epoch {epoch+1}/{epochs}, Loss: {running_loss/len(train_loader):.4f}, Accuracy: {acc:.2f}%")

#Test
correct = 0
total = 0

with torch.no_grad():
    for images, labels in test_loader:
        outputs = forward(images)
        _, predicted = torch.max(outputs, 1)
        total += labels.size(0)
        correct += (predicted == labels).sum().item()

test_acc = 100 * correct / total
print(f"Test Accuracy: {test_acc:.2f}%")

