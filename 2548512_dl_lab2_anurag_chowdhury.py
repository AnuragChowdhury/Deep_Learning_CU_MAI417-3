#Shallow Network (1 Hidden Layer)
A1 = nn.Linear(784, 256)
A2 = nn.Linear(256, 10)

paramsA = list(A1.parameters()) + list(A2.parameters())

def forwardA(x):
    x = x.view(-1, 784)
    x = F.relu(A1(x))
    x = A2(x)
    return x

#Medium Network (3 Hidden Layers)
B1 = nn.Linear(784, 512)
B2 = nn.Linear(512, 256)
B3 = nn.Linear(256, 128)
B4 = nn.Linear(128, 10)

paramsB = list(B1.parameters()) + list(B2.parameters()) + \
          list(B3.parameters()) + list(B4.parameters())

def forwardB(x):
    x = x.view(-1, 784)
    x = F.relu(B1(x))
    x = F.relu(B2(x))
    x = F.relu(B3(x))
    x = B4(x)
    return x

#Deep Network (5 Hidden Layers)
C1 = nn.Linear(784, 512)
C2 = nn.Linear(512, 512)
C3 = nn.Linear(512, 256)
C4 = nn.Linear(256, 128)
C5 = nn.Linear(128, 64)
C6 = nn.Linear(64, 10)

paramsC = list(C1.parameters()) + list(C2.parameters()) + \
          list(C3.parameters()) + list(C4.parameters()) + \
          list(C5.parameters()) + list(C6.parameters())

def forwardC(x):
    x = x.view(-1, 784)
    x = F.relu(C1(x))
    x = F.relu(C2(x))
    x = F.relu(C3(x))
    x = F.relu(C4(x))
    x = F.relu(C5(x))
    x = C6(x)
    return x

#Training
def train_model(forward_fn, params, epochs=5):
    optimizer = optim.Adam(params, lr=0.001)
    criterion = nn.CrossEntropyLoss()

    for epoch in range(epochs):
        running_loss, correct, total = 0, 0, 0

        for images, labels in train_loader:
            outputs = forward_fn(images)
            loss = criterion(outputs, labels)

            optimizer.zero_grad()
            loss.backward()
            optimizer.step()

            running_loss += loss.item()
            _, predicted = torch.max(outputs, 1)
            total += labels.size(0)
            correct += (predicted == labels).sum().item()

        print(f"Epoch {epoch+1}, Loss = {running_loss/len(train_loader):.4f}, "
              f"Train Acc = {100*correct/total:.2f}%")



#Test
def evaluate_model(forward_fn):
    correct, total = 0, 0
    with torch.no_grad():
        for images, labels in test_loader:
            outputs = forward_fn(images)
            _, predicted = torch.max(outputs, 1)
            total += labels.size(0)
            correct += (predicted == labels).sum().item()
    return 100 * correct / total

#1-Layer
print("\nTraining Model A (1 Hidden Layer)")
train_model(forwardA, paramsA)
print("Test Accuracy:", evaluate_model(forwardA))

#3-Layer
print("\nTraining Model B (3 Hidden Layers)")
train_model(forwardB, paramsB)
print("Test Accuracy:", evaluate_model(forwardB))

#5-Layer
print("\nTraining Model C (5 Hidden Layers)")
train_model(forwardC, paramsC)
print("Test Accuracy:", evaluate_model(forwardC))

"""#ADVANCED TASK 2 – Activation Function Study"""

def relu(x):
    return F.relu(x)

def sigmoid(x):
    return torch.sigmoid(x)

def tanh(x):
    return torch.tanh(x)

def leaky(x):
    return F.leaky_relu(x, negative_slope=0.01)

def forward_act(x, activation):
    x = x.view(-1, 784)
    x = activation(B1(x))
    x = activation(B2(x))
    x = activation(B3(x))
    x = B4(x)
    return x

#Training
def train_with_activation(activation_fn, params, epochs=5):
    optimizer = optim.Adam(params, lr=0.001)
    criterion = nn.CrossEntropyLoss()

    for epoch in range(epochs):
        running_loss = 0
        correct = 0
        total = 0

        for images, labels in train_loader:
            outputs = forward_act(images, activation_fn)
            loss = criterion(outputs, labels)

            optimizer.zero_grad()
            loss.backward()
            optimizer.step()

            running_loss += loss.item()
            _, predicted = torch.max(outputs, 1)
            total += labels.size(0)
            correct += (predicted == labels).sum().item()

        print(f"Epoch {epoch+1}, Loss={running_loss/len(train_loader):.4f}, "
              f"Accuracy={100*correct/total:.2f}%")

#Testing
def test_with_activation(activation_fn):
    correct = 0
    total = 0
    with torch.no_grad():
        for images, labels in test_loader:
            outputs = forward_act(images, activation_fn)
            _, predicted = torch.max(outputs, 1)
            total += labels.size(0)
            correct += (predicted == labels).sum().item()

    return 100 * correct / total

#ReLU
print("\nUsing ReLU Activation")
train_with_activation(relu, paramsB)
print("Test Accuracy:", test_with_activation(relu))

#Sigmoid
print("\nUsing Sigmoid Activation")
train_with_activation(sigmoid, paramsB)
print("Test Accuracy:", test_with_activation(sigmoid))

#Tanh
print("\nUsing Tanh Activation")
train_with_activation(tanh, paramsB)
print("Test Accuracy:", test_with_activation(tanh))

#Leaky ReLU
print("\nUsing Leaky ReLU Activation")
train_with_activation(leaky, paramsB)
print("Test Accuracy:", test_with_activation(leaky))

